STATUS_LABEL = {
    "full":    """קיים – מלא""",
    "partial": """קיים – חלקי""",
    "diff":    """קיים – גישה שונה""",
    "none":    """לא קיים""",
    "na":     """לא רלוונטי""",
}

def esc(s):
    return html_escape_mod.escape(s, quote=False)

def cell(status, text):
    """תא של קובץ בודד בטבלה: תג סטטוס + טקסט תיאור."""
    label = STATUS_LABEL[status]
    body = esc(text).replace("\n", "<br>")
    return f'<td class="fc {status}"><span class="tag {status}">{label}</span><div class="ct">{body}</div></td>'

def rec_cell(text):
    body = esc(text).replace("\n", "<br>")
    return f'<td class="rec"><div class="ct">{body}</div></td>'

def row(item, f1, f2, f3, f4, rec, note=None):
    out = "<tr>"
    note_html = f'<div class="note">{esc(note)}</div>' if note else ""
    out += f'<td class="item">{esc(item)}{note_html}</td>'
    out += cell(*f1)
    out += cell(*f2)
    out += cell(*f3)
    out += cell(*f4)
    out += rec_cell(rec)
    out += "</tr>"
    return out

def section(sid, title, intro, rows_data):
    rows_html = "\n".join(
        row(r["item"], r["f1"], r["f2"], r["f3"], r["f4"], r["rec"], r.get("note"))
        for r in rows_data
    )
    intro_html = f'<p class="intro">{esc(intro)}</p>' if intro else ""
    header_cells = "".join(
        f'<th class="fc-h {c["cls"]}"><span class="hnum">{c["num"]}</span>{esc(c["nick"])}<span class="fname">{esc(c["file"])}</span></th>'
        for c in COL_META
    )
    return f'''
<section class="sec" id="{sid}">
  <h2>{esc(title)}</h2>
  {intro_html}
  <div class="twrap">
  <table>
    <thead>
      <tr>
        <th class="item-h">פריט / תכונה</th>
        {header_cells}
        <th class="rec-h">המלצה ליישום בקובץ המושלם</th>
      </tr>
    </thead>
    <tbody>
      {rows_html}
    </tbody>
  </table>
  </div>
</section>
'''


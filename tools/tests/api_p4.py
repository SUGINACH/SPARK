from api_common import *
def phase(page):
    def crm_ready():
        page.wait_for_function("typeof globalCustomers !== 'undefined' && globalCustomers.length >= 2")
    step('a. no connection configured -> demo mode in the same site')
    page.goto(BASE + 'index.html'); page.evaluate("localStorage.removeItem('bs:api')")
    page.goto(BASE + 'index.html'); page.wait_for_url('**/crm.html**'); crm_ready()
    print('   mode:', page.evaluate('bsDemo.config().mode'), '| bar:', page.inner_text('#bsdemo-mode'), '| demo customers:', page.evaluate('globalCustomers.length'))
    step('b. connection dialog: wrong key, right key, save')
    page.evaluate('bsDemo.openConnect()')
    page.fill('#bsc-url', API_URL); page.fill('#bsc-key', 'WRONG'); page.click('#bsc-test'); page.wait_for_function("document.getElementById('bsc-msg').textContent.length > 8")
    print('   wrong key  ->', page.inner_text('#bsc-msg'))
    page.fill('#bsc-key', 'TESTKEY'); page.click('#bsc-test'); page.wait_for_function("document.getElementById('bsc-msg').textContent.includes('תקין')")
    print('   right key  ->', page.inner_text('#bsc-msg'))
    page.click('#bsc-save'); page.wait_for_url('**/crm.html**'); crm_ready()
    print('   after save: mode', page.evaluate('bsDemo.config()'), '| bar:', page.inner_text('#bsdemo-mode'))
    step('c. stored key is wrong -> the site asks once and recovers')
    n0 = len(dialogs)
    page.evaluate("localStorage.setItem('bs:api', JSON.stringify({url: '%s', key: 'WRONG', exportMode: 'server'}))" % API_URL)
    page.goto(BASE + 'crm.html'); crm_ready()
    prompts = [d for d in dialogs[n0:] if d[0] == 'prompt']
    print('   prompts shown:', len(prompts), '| key after:', json.loads(page.evaluate("localStorage.getItem('bs:api')"))['key'], '| customers:', page.evaluate('globalCustomers.length'))
    step('d. unknown action and unreachable server give clear errors')
    err = page.evaluate("new Promise(res => google.script.run.withFailureHandler(e => res(e.message + ' | code=' + e.code)).doesNotExist())")
    print('   unknown action ->', err)
    page.evaluate("localStorage.setItem('bs:api', JSON.stringify({url: 'http://localhost:8999/exec', key: 'TESTKEY'}))")
    page.goto(BASE + 'print.html?clientId=BS-1001'); page.wait_for_timeout(1500)
    err2 = page.evaluate("new Promise(res => google.script.run.withFailureHandler(e => res(e.message)).getInitialData())")
    print('   unreachable    ->', err2[:120])
    step('e. server log: no preflight, only text/plain POSTs')
    lg = server_log()
    print('   OPTIONS:', sum(1 for e in lg['log'] if e['m'] == 'OPTIONS'), '| POST content-types:', sorted({e['ct'] for e in lg['log'] if e['m'] == 'POST'}), '| actions:', sorted({e['action'] for e in lg['log'] if e['m'] == 'POST'}))
    step('f. disconnect from the dialog returns to demo mode')
    page.evaluate("localStorage.setItem('bs:api', JSON.stringify({url: '%s', key: 'TESTKEY'}))" % API_URL)
    page.goto(BASE + 'crm.html'); crm_ready(); page.evaluate('bsDemo.openConnect()'); page.click('#bsc-off'); page.wait_for_url('**/crm.html**'); crm_ready()
    print('   mode now:', page.evaluate('bsDemo.config().mode'), '| bar:', page.inner_text('#bsdemo-mode'))
run(phase, preset_cfg=False, key='TESTKEY', prompt_answer='TESTKEY')

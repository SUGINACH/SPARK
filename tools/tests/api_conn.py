from api_common import *
def ck(name, cond, extra=''): print(('✅ ' if cond else '🔴 ') + name + (('  -> ' + str(extra)) if extra != '' else ''), flush=True)
def phase(page):
    def crm_ready(): page.wait_for_function("typeof globalCustomers !== 'undefined' && globalCustomers.length >= 2")
    step('a. no connection configured -> demo mode')
    page.goto(BASE + 'index.html'); page.evaluate("localStorage.removeItem('bs:api'); sessionStorage.clear()")
    page.goto(BASE + 'index.html'); page.wait_for_url('**/crm.html**'); crm_ready()
    ck('demo mode with seeded customers (no login in demo)', page.evaluate('bsDemo.config().mode') == 'demo' and page.evaluate('globalCustomers.length') == 2 and page.locator('#bsdemo-login').count() == 0)
    step('b. connection dialog: bad address, good address, save -> login screen')
    page.evaluate('bsDemo.openConnect()')
    page.fill('#bsc-url', 'http://localhost:8999/exec'); page.click('#bsc-test'); page.wait_for_function("document.getElementById('bsc-msg').textContent.includes('לא ניתן')")
    ck('unreachable address gives a clear message', True, page.inner_text('#bsc-msg')[:70])
    page.fill('#bsc-url', API_URL); page.click('#bsc-test'); page.wait_for_function("document.getElementById('bsc-msg').textContent.includes('תקין')")
    ck('test without any key succeeds and shows the login methods', 'סיסמה' in page.inner_text('#bsc-msg'), page.inner_text('#bsc-msg'))
    ck('first connection defaults the export mode to server', page.input_value('#bsc-exp') == 'server')
    page.click('#bsc-save'); page.wait_for_selector('#bsdemo-login')
    ck('after saving, the site asks to log in', page.evaluate('bsDemo.config().mode') == 'api')
    page.fill('#bsl-user', 'ora'); page.fill('#bsl-pass', 'Long-Passw0rd-123'); page.click('#bsl-go'); crm_ready()
    ck('logged in; export mode stayed server', page.evaluate('bsDemo.config().exportMode') == 'server' and page.evaluate('bsDemo.config().user') == 'ora')
    step('c. errors are clear')
    err = page.evaluate("new Promise(res => google.script.run.withFailureHandler(e => res(e.message + ' | ' + e.code)).doesNotExist())")
    ck('unknown action', 'unknown_action' in err, err)
    page.evaluate("sessionStorage.clear(); localStorage.setItem('bs:api', JSON.stringify({url: 'http://localhost:8999/exec', key: 'x'}))")
    page.goto(BASE + 'print.html?clientId=BS-1001'); page.wait_for_timeout(1500)
    err2 = page.evaluate("new Promise(res => google.script.run.withFailureHandler(e => res(e.message)).getInitialData())")
    ck('unreachable server -> Hebrew message', 'לא ניתן להגיע' in err2, err2[:90])
    step('d. disconnect returns to demo mode')
    page.evaluate("localStorage.setItem('bs:api', JSON.stringify({url: '%s', exportMode: 'server'}))" % API_URL)
    page.goto(BASE + 'crm.html'); page.wait_for_selector('#bsdemo-login'); page.click('#bsl-cancel')
    page.evaluate('bsDemo.openConnect()'); page.click('#bsc-off'); page.wait_for_url('**/crm.html**'); crm_ready()
    ck('mode is demo again', page.evaluate('bsDemo.config().mode') == 'demo' and 'מצב דמו' in page.inner_text('#bsdemo-mode'))
run(phase, reset=False, preset_cfg=False)
